// Builds supabase/2027-retention.sql from the TEAMS array in "IPL Squads Board.html".
// Run: node scripts/gen-retention-sql.mjs
// Also creates public/players/<TEAM>/ folders with a _filenames.txt listing the
// photo file names each player needs.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const html = fs.readFileSync(path.join(root, 'IPL Squads Board.html'), 'utf8');

const start = html.indexOf('const TEAMS=');
const end = html.indexOf('];', start);
if (start < 0 || end < 0) throw new Error('TEAMS array not found');
// Data-only array literal from our own file.
const TEAMS = new Function(`return ${html.slice(start + 'const TEAMS='.length, end + 1)}`)();

const SEASON = 2027;
export const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const q = (s) => (s == null || s === '' ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

const rows = [];
const folders = {};
for (const t of TEAMS) {
    folders[t.id] = [];
    t.p.forEach((entry, i) => {
        const [name, price, country, flags = ''] = entry.split('|');
        const photoKey = `${t.id}/${slug(name)}`;
        folders[t.id].push(`${slug(name)}.png   (${name})`);
        rows.push(
            `  (${SEASON}, ${q(t.id)}, ${q(name)}, ${Number(price)}, ${q(country)}, ${flags.includes('C')}, ${flags.includes('W')}, ${q(flags.includes('T') ? 'trade' : 'squad')}, ${i}, ${q(photoKey)})`
        );
    });
}

const sql = `-- IPL 2027 retention: squads + per-team purse.
-- Generated by scripts/gen-retention-sql.mjs from "IPL Squads Board.html".
-- Run once in the Supabase SQL editor. Safe to re-run (skips existing rows).

create table if not exists squad_players (
  id uuid primary key default gen_random_uuid(),
  season int not null,
  team_code text not null,
  player_name text not null,
  price numeric(6,2) not null default 0,
  country text,                                    -- null = Indian
  is_captain boolean not null default false,
  is_wk boolean not null default false,
  acquired_via text not null default 'squad'
    check (acquired_via in ('squad','trade','added','auction')),
  status text not null default 'pending'
    check (status in ('pending','retained','released')),
  sort_order int not null default 0,
  photo_key text,                                  -- e.g. CSK/sanju-samson -> public/players/CSK/sanju-samson.png
  status_changed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (season, team_code, player_name)
);

create index if not exists idx_squad_players_season_team on squad_players(season, team_code);
create index if not exists idx_squad_players_status_changed on squad_players(status_changed_at desc);

create table if not exists season_teams (
  season int not null,
  team_code text not null,
  purse numeric(6,2),                              -- set by admin; null = not announced
  updated_at timestamptz not null default now(),
  primary key (season, team_code)
);

-- updated_at triggers (function exists from schema.sql; recreate to be safe)
create or replace function update_updated_at_column()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists update_squad_players_updated_at on squad_players;
create trigger update_squad_players_updated_at before update on squad_players
  for each row execute function update_updated_at_column();

drop trigger if exists update_season_teams_updated_at on season_teams;
create trigger update_season_teams_updated_at before update on season_teams
  for each row execute function update_updated_at_column();

-- Security: everyone can read, nobody can write with the public key.
-- Writes go through /api/retention, which uses the service role key.
alter table squad_players enable row level security;
alter table season_teams enable row level security;

drop policy if exists "public read squad_players" on squad_players;
create policy "public read squad_players" on squad_players for select using (true);

drop policy if exists "public read season_teams" on season_teams;
create policy "public read season_teams" on season_teams for select using (true);

-- Realtime (send full old row on delete/update so the client can remove it)
alter table squad_players replica identity full;
alter table season_teams replica identity full;
do $$
begin
  begin
    alter publication supabase_realtime add table squad_players;
  exception when duplicate_object then null;
  end;
  begin
    alter publication supabase_realtime add table season_teams;
  exception when duplicate_object then null;
  end;
end $$;

-- Seed: one purse row per team (purse filled in later by admin)
insert into season_teams (season, team_code) values
${TEAMS.map((t) => `  (${SEASON}, ${q(t.id)})`).join(',\n')}
on conflict do nothing;

-- Seed: current squads (${rows.length} players), all pending
insert into squad_players
  (season, team_code, player_name, price, country, is_captain, is_wk, acquired_via, sort_order, photo_key)
values
${rows.join(',\n')}
on conflict (season, team_code, player_name) do nothing;
`;

fs.writeFileSync(path.join(root, 'supabase', '2027-retention.sql'), sql);

// Photo folders
const playersDir = path.join(root, 'public', 'players');
for (const [team, files] of Object.entries(folders)) {
    const dir = path.join(playersDir, team);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(
        path.join(dir, '_filenames.txt'),
        `Photos for ${team}. Use these exact file names (.png, .jpg, .jpeg, .webp or .avif all work).\n` +
        `Square-ish head-and-shoulders shots look best. Missing photos show the default silhouette.\n\n` +
        files.join('\n') + '\n'
    );
}

console.log(`players: ${rows.length}`);
for (const t of TEAMS) console.log(`  ${t.id}: ${t.p.length}`);
