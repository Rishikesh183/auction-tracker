-- IPL 2027 trade history (shown in the "Trades" tab).
-- Run once in the Supabase SQL editor. Safe to re-run.
--
-- Each row is one trade. legs = the players who moved:
--   [{ "player_id": uuid|null, "player_name": "...", "from_team": "SRH", "to_team": "CSK",
--      "price": 6, "photo_key": "CSK/liam-livingstone", "country": "ENG" }, ...]
-- Admin trades (Retention control -> Trade) move the players AND add a row here.

create table if not exists trades (
  id uuid primary key default gen_random_uuid(),
  seq bigint generated by default as identity,         -- display order (newest = highest)
  season int not null,
  team_a text not null,
  team_b text not null,
  legs jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_trades_season_seq on trades(season, seq desc);

-- Everyone can read; writes only via /api/retention (service role key).
alter table trades enable row level security;
drop policy if exists "public read trades" on trades;
create policy "public read trades" on trades for select using (true);

